package ai

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"strings"
	"time"

	"shop24/internal/domain/models"
	"shop24/internal/domain/storefront"
)

const systemPrompt = `You design storefront configuration for a small online shop.
Return one JSON object and nothing else. Do not return HTML, JavaScript, Vue, CSS, or any executable code.
Use only these section types: hero, product_grid, featured_products, about, announcement, categories, newsletter.
Each section object has id, type, visible, and exactly one property object matching its type: hero, productGrid, featured, about, announcement, categories, or newsletter.
Theme name must be editorial, minimal, luxury, bold, playful, mono, or dark.
Fonts must be one of: Instrument Serif, Fraunces, Newsreader, Outfit, Figtree, Literata.
Colors must be hex values like #112233.
Radius must be none, sm, md, or lg. Image ratio must be square, portrait, or landscape.
Navigation targets must be home, products, about, or cart.
Do not invent products. Product sections are filled from the seller's live catalog.
When revising a design, change only what the prompt asks for and keep the rest.`

type OpenAI struct {
	key     string
	baseURL string
	model   string
	client  *http.Client
}

func NewOpenAI(key, baseURL, model string, timeout time.Duration) *OpenAI {
	return &OpenAI{
		key: key, baseURL: strings.TrimRight(baseURL, "/"), model: model,
		client: &http.Client{Timeout: timeout},
	}
}

func (o *OpenAI) Name() string { return "openai" }

func (o *OpenAI) Generate(ctx context.Context, prompt string, store StoreContext) (Result, error) {
	return o.complete(ctx, prompt, nil, store, "generate")
}

func (o *OpenAI) Refine(ctx context.Context, prompt string, current models.StorefrontConfig, store StoreContext) (Result, error) {
	return o.complete(ctx, prompt, &current, store, "refine")
}

func (o *OpenAI) complete(ctx context.Context, prompt string, current *models.StorefrontConfig, store StoreContext, mode string) (Result, error) {
	user, err := json.Marshal(map[string]any{
		"mode": mode, "prompt": prompt, "store": store, "current": current,
	})
	if err != nil {
		return Result{}, err
	}
	body, err := json.Marshal(map[string]any{
		"model":           o.model,
		"temperature":     0.4,
		"response_format": map[string]string{"type": "json_object"},
		"messages": []map[string]string{
			{"role": "system", "content": systemPrompt},
			{"role": "user", "content": string(user)},
		},
	})
	if err != nil {
		return Result{}, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, o.baseURL+"/chat/completions", bytes.NewReader(body))
	if err != nil {
		return Result{}, err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+o.key)
	res, err := o.client.Do(req)
	if err != nil {
		return Result{}, err
	}
	defer res.Body.Close()
	payload, err := io.ReadAll(io.LimitReader(res.Body, 1<<20))
	if err != nil {
		return Result{}, err
	}
	if res.StatusCode >= 300 {
		return Result{}, fmt.Errorf("design provider status %d", res.StatusCode)
	}
	var parsed struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.Unmarshal(payload, &parsed); err != nil {
		return Result{}, err
	}
	if len(parsed.Choices) == 0 || strings.TrimSpace(parsed.Choices[0].Message.Content) == "" {
		return Result{}, fmt.Errorf("design provider returned an empty response")
	}
	var cfg models.StorefrontConfig
	if err := json.Unmarshal([]byte(extractJSON(parsed.Choices[0].Message.Content)), &cfg); err != nil {
		return Result{}, err
	}
	return Result{
		Config:   storefront.Normalize(cfg),
		Provider: o.Name(),
		Summary:  "Generated by the configured model and checked against the storefront schema.",
	}, nil
}

func extractJSON(content string) string {
	content = strings.TrimSpace(content)
	if !strings.HasPrefix(content, "```") {
		return content
	}
	content = strings.TrimPrefix(content, "```json")
	content = strings.TrimPrefix(content, "```")
	if end := strings.LastIndex(content, "```"); end >= 0 {
		content = content[:end]
	}
	return strings.TrimSpace(content)
}
